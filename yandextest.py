def is_bitwise_or_even(arr):
    """
    Определяет, является ли побитовое ИЛИ всех элементов массива чётным.
    """
    result = 0
    for num in arr:
        # Явная запись побитового ИЛИ
        result = result | num

    # Проверка чётности
    return result % 2 == 0

# Примеры
print(is_bitwise_or_even([1, 2, 3]))  # 1|2|3 = 3 → "Нечётное (3)"
print(is_bitwise_or_even([2, 4, 6]))  # 2|4|6 = 6 → "Чётное (6)"
print(is_bitwise_or_even([1, 3, 5]))  # 1|3|5 = 7 → "Нечётное (7)"
print(is_bitwise_or_even([8, 16, 32]))  # 8|16|32 = 56 → "Чётное (56)"
print(is_bitwise_or_even([]))  # "Чётное (0)"


def min_power_of_two(numbers):
    """
    Находит наименьшую степень 2, которая >= сумме чисел в массиве.

    Алгоритм:
    1. Вычисляем сумму всех элементов массива
    2. Если сумма <= 0, то возвращаем 1 (2^0 = 1 — минимальная степень 2)
    3. Иначе находим минимальную степень 2, которая >= сумме:
       - Начинаем с 1 и умножаем на 2 пока не превысим сумму
    """
    # Шаг 1: суммируем все числа — O(n)
    total = sum(numbers)

    # Шаг 2: обработка неположительной суммы
    if total <= 0:
        return 1  # 2^0 = 1

    # Шаг 3: находим минимальную степень 2 >= total — O(log S)
    power = 1
    while power < total:
        power = power * 2  # Умножаем на 2

    return power


# Примеры работы
print(min_power_of_two([1, 2, 3]))  # сумма=6,  ответ=8  (2^3)
print(min_power_of_two([5, 5]))  # сумма=10, ответ=16 (2^4)
print(min_power_of_two([16]))  # сумма=16, ответ=16 (2^4)
print(min_power_of_two([1, 1, 1, 1]))  # сумма=4,  ответ=4  (2^2)
print(min_power_of_two([100]))  # сумма=100,ответ=128(2^7)
print(min_power_of_two([0, 0, 0]))  # сумма=0,  ответ=1  (2^0)
print(min_power_of_two([-5, 3]))  # сумма=-2, ответ=1  (2^0)
print(min_power_of_two([]))  # сумма=0,  ответ=1  (2^0)