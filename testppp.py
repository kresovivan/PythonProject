# ===================================================================
# БАЗОВЫЕ УПРАВЛЯЮЩИЕ ФУНКЦИИ (КОНТРОЛЛЕРЫ)
# ===================================================================
def do_twice(f):
    f()  # Вызов функции f (первый раз)
    f()  # Вызов функции f (второй раз)


def do_four(f):
    do_twice(f)  # Вызывает f два раза
    do_twice(f)  # Ещё два раза, всего получаем = всего 4 вызова


def one_four_one(f, g, h):
    f()          # Первая функция вызывается один раз
    do_four(g)   # Вторая функция вызывается четыре раза (через do_four)
    h()          # Третья функция вызывается один раз


# ===================================================================
# ПРИМИТИВНЫЕ ФУНКЦИИ-КИРПИЧИКИ (БАЗОВЫЕ ДЕЙСТВИЯ)
# ===================================================================
def print_plus():
    """Печатает символ '+' без перевода строки."""
    print('+', end=' ')
    

def print_dash():
    """Печатает символ '-' без перевода строки."""
    print('-', end=' ')


def print_bar():
    """Печатает символ '|' (вертикальная черта) без перевода строки."""
    print('|', end=' ')


def print_space():
    """Печатает пробел без перевода строки."""
    print(' ', end=' ')


def print_end():
    """
    Печатает пустую строку (перевод на новую строку).
    Завершает текущую строку на экране.
    """
    print()


def nothing():
    """
    Функция-пустышка (аналог "pass").
    Используется как заглушка в шаблоне one_four_one,
    когда какое-то действие не требуется.
    """
    "do nothing"  # Это просто комментарий в теле функции


# ===================================================================
# ФУНКЦИИ СРЕДНЕГО УРОВНЯ (КОМПОНЕНТЫ ЯЧЕЙКИ)
# ===================================================================
def print1beam():
    """
    Печатает одну "балку": "+----".
    Использует шаблон one_four_one с действиями:
    - ничего (nothing)
    - 4 дефиса (print_dash)
    - 1 плюс (print_plus)
    """
    one_four_one(nothing, print_dash, print_plus)


def print1post():
    """
    Печатает один "столб": "|    ".
    Использует шаблон one_four_one с действиями:
    - ничего (nothing)
    - 4 пробела (print_space)
    - 1 вертикальная черта (print_bar)
    """
    one_four_one(nothing, print_space, print_bar)


# ===================================================================
# ФУНКЦИИ ПОСТРОЕНИЯ ЛИНИЙ (ФОРМИРОВАНИЕ РЯДОВ)
# ===================================================================
def print4beams():
    """
    Печатает горизонтальную линию сетки: "+----+----+----+----+"
    Шаблон one_four_one:
    - print_plus (печатает первый +)
    - print1beam (печатает "----+" четыре раза)
    - print_end (перевод строки)
    """
    one_four_one(print_plus, print1beam, print_end)


def print4posts():
    """
    Печатает вертикальные стенки строки: "|    |    |    |    |"
    Шаблон one_four_one:
    - print_bar (печатает первую |)
    - print1post (печатает "    |" четыре раза)
    - print_end (перевод строки)
    """
    one_four_one(print_bar, print1post, print_end)


# ===================================================================
# ФУНКЦИЯ ПОСТРОЕНИЯ РЯДА ЯЧЕЕК
# ===================================================================
def print_row():
    """
    Печатает полный ряд сетки (строку ячеек):
    - 4 раза print4posts (вертикальные стенки + пробелы)
    - 1 раз print4beams (горизонтальная линия с плюсами)
    Шаблон one_four_one:
    - nothing (ничего не делаем сначала)
    - print4posts (вызов 4 раза для создания тела ряда)
    - print4beams (завершающая линия)
    """
    one_four_one(nothing, print4posts, print4beams)


# ===================================================================
# ГЛАВНАЯ ФУНКЦИЯ - ПОСТРОЕНИЕ ВСЕЙ СЕТКИ
# ===================================================================
def print_grid():
    """
    Печатает полную сетку 4x4.
    Шаблон one_four_one:
    - print4beams (верхняя граница сетки)
    - print_row (тело сетки с ячейками - вызывается 4 раза)
    - nothing (ничего не делаем в конце)
    """
    one_four_one(print4beams, print_row, nothing)

# ===================================================================
# ЗАПУСК ПРОГРАММЫ
# ===================================================================
print_grid()  # Вызов главной функции - печать сетки 4x4