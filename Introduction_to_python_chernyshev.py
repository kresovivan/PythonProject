"""Объектно-ориентированное программирование
В основе ООП лежит понятие объект, который представляет собой некую сущность предметной
области, в рамках которой ведется разработка приложения.
В некоторых случаях описываемый объект может не входить в предметную область и является
порождением нашего воображения, но на него возлагается ряд обязанностей, что позволяет
нам в целом упростить код разрабатываемого приложения.

Объекты описываются в коде классами.
Класс это абстракция, позволяющая нам перенести состояние и поведение объекта предметной
области в код.    

1.Под состоянием понимается некоторый набор аттрибутов, которые позволяют описать из чего состоит 
объект и какие характеристики ему присущи.
Например: марка автомобиля, ее цвет, объем двигателя, тип топлива.
2.Под поведением понимается некоторый набор действий, которые объект может совершать над своим
внутренним состоянием. 
Автомобиль может стоять на месте, его можно завести, начать движение, повернуть налево или направо, 
ускориться.

Состояние объекта, при его описании классом на языке программирования, переводится в переменные
реализуемого класса, а поведение объекта - в методы!!!

При это не всегда класс описывает один объект.
Все зависит от структуры того объекта, который необходимо перенести от структуры того объекта,
который необходимо перенести в программный код, в связи с чем некоторые объекты могут
быть описаны не одним, а целым набором классов.


До тех пор, пока разработчик явным образом не создал экземпляр класса (вызвал конструктор),
он существует как текст и только в момент его создания мы можем говорить, что разрабатываемое 
приложение оперирует объектом, так как под него выделяется память, инициализируется его
состояние и появляется возможность его изменить путем вызова метода объекта.

Наследование - новый уровень абстракции.
Позволяет создавать новые классы на основе существующих. 
Тот класс, от которого происходит наследование принято называть базовым классом (суперклассом
или родительским классом), а класс, который наследуется от базового - производным классом.
Производный класс наследует состояние и поведение базового класса, что позволяет повторно
использовать имеющийся код, но при этом необходимо всегда придерживаться интерфейса, который
создает базовый класс.
Также производный класс может объявлять собственные переменные и методы, тем самым расширяя состояние
и поведение базового класса. Именно здесь и кроется ответ на вопрос.
Абстракция - это обобщение, а производный класс добавляет к базовому дополнительные детали.
Таким образом базовый класс, от которого производится наследование, всегда будет более
абстрактным нежели производный!!!

Полиморфизм - позволяет переопределять реализацию метода базового класса. После чего, например,
при создании экземпляра производного класса при вызове метода "набора скорости" уже будет 
вызываться не реализация базового класса, а переопределенная в производном.

Интерфейс это переменные и методы класса, у которых публичная область видимости.
Это значит что любой разработчик который импортирует ваш класс, может получить к ним доступ
без опасения поломать что-либо в логике его работы.
Мы можем работать с экземпляром производного класса через интерфейс базового используя операцию 
приведения.    """
