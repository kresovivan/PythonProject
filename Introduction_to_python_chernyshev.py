"""Генераторные функции и выражения
являются синтаксическим сахаром для простого написания итератора и позволяет откладывать 
создание результатов всякий раз, когда это возможно.
Из-за того, что ни та ни другая конструкция не создает сразу весь список с результатами,
они экономят пространство памяти и позволяют распределить время вычислений по запросам результатов
Эти функции специально компилируются в объект, который поддерживает протокол итерации.
В отличие от нормальных функций которые возвращают значение и прекращают работу, генераторные
функции автоматически приостанавливают и возобновляют свое выполнение и состояние вокруг точки
генерации значений.




            return	                              yield
Завершает функцию навсегда	            Приостанавливает функцию
Возвращает значение и "умирает"	        Возвращает значение и "засыпает"
Функцию можно вызвать только раз	    Функцию можно вызывать много раз
Не помнит своё состояние	            Помнит всё (переменные, позицию)


"""


def gen_test():
    n = 0
    while n < 3:
        yield n
        n += 1


for x in gen_test():
    print(x)  # 0,1,2

"""Чтобы лучше понять принцип работы реализуем следующую функцию, тело
которой состоит только из  yield"""


def gen_surprise_test():
    yield 0
    yield 1
    yield 2


for x in gen_surprise_test():
    print(x)  # 0,1,2

"""Таким образом, генераторные функции позволяют избежать выполнения всей работы заранее, что
особенно полезно когда результирующие списки большие или получение
каждого значения требует длительных вычислений"""


def gen_test_send(N):
    for x in range(N):
        Y = yield x
