"""Операции над множествами
Пересчение
Симметричная разница
Разница
Объединение
"""

A = {0, 1, 1, 2, 3, 9, 4, 5, 6, 6, 7, 8, 9}
B = {1, 3, 6, 10, 15, 21, 28, 36, 45}
